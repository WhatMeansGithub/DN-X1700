#!/usr/bin/env python3
"""Generate site/patches.js (the web patcher's data) from patches/*.yaml.

The expected result hash is taken from a real build with tools/build.py, so the browser tool and the Python tool are
guaranteed to produce the same image. Needs firmware/original/X1700FW.BIN. Run again whenever a patch changes.
"""
import json
import pathlib
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
subprocess.run([sys.executable, str(ROOT / "tools/build.py"), "--date", "site"], check=True, stdout=subprocess.DEVNULL)

names = sorted(p.stem for p in (ROOT / "patches").glob("[0-9][0-9][0-9]-*.yaml"))
manifest = json.loads(next((ROOT / "firmware/builds").glob("X1700FW-site-*.manifest.json")).read_text())

patches = []
for n in names:
    doc = yaml.safe_load((ROOT / "patches" / f"{n}.yaml").read_text())
    for e in doc["patches"]:
        patches.append({"patch": n, "offset": e["offset"], "expect": e["expect"], "new": e["new"],
                        "reason": " ".join(e["reason"].split())})

data = {"originalSha256": manifest["original_sha256"], "resultSha256": manifest["sha256"], "patchSets": names, "patches": patches}
out = ROOT / "site/patches.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// GENERATED by tools/gen_site_data.py from patches/*.yaml. Do not edit.\n"
               "globalThis.X1700_PATCHES = " + json.dumps(data, indent=1) + ";\n")
(ROOT / "patches/patches.json").write_text(json.dumps(data, indent=1) + "\n")     # for tools/x1700_patcher.py (no PyYAML needed)
print(f"wrote {out.relative_to(ROOT)} and patches/patches.json: {len(patches)} patch entries, result sha256 {data['resultSha256']}")
