#!/usr/bin/env python3
"""Generate the web patcher's data from the patch files.

  X1700: patches/*.yaml       -> site/patches.js (X1700_PATCHES) and patches/patches.json (for tools/x1700_patcher.py)
  X1600: patches/x1600/*.yaml -> site/x1600/patches.js (X1600_PATCHES). Experimental page: not tested on a real X1600.
  X600:  patches/x600/*.yaml  -> site/x600/patches.js (X600_PATCHES). Experimental page: not tested on a real X600; CRC-32 integrity rule.

The expected result hash is taken from a real build with tools/build.py, so the browser tool and the Python build are
guaranteed to produce the same image. Needs the original images in firmware/original/ (X1700FW.BIN, and X1600FW.BIN for the
X1600 page; a missing X1600 original skips that page). Run again whenever a patch changes.
"""
import json
import pathlib
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import models  # noqa: E402


def site_data(model):
    m = models.get(model)
    subprocess.run([sys.executable, str(ROOT / "tools/build.py"), "--model", model, "--date", "site"], check=True,
                   stdout=subprocess.DEVNULL)
    names = sorted(p.stem for p in m["patch_dir"].glob("[0-9][0-9][0-9]-*.yaml"))
    stem = m["fw_name"].removesuffix(".BIN")
    manifest = json.loads(next((ROOT / "firmware/builds").glob(f"{stem}-site-*.manifest.json")).read_text())
    patches = []
    for n in names:
        doc = yaml.safe_load((m["patch_dir"] / f"{n}.yaml").read_text())
        for e in doc["patches"]:
            patches.append({"patch": n, "offset": e["offset"], "expect": e["expect"], "new": e["new"],
                            "reason": " ".join(e["reason"].split())})
    return {"originalSha256": manifest["original_sha256"], "resultSha256": manifest["sha256"], "patchSets": names, "patches": patches}


# X1700 (unchanged format: the page and the program default to the X1700's size and file name)
data = site_data("X1700")
out = ROOT / "site/patches.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// GENERATED by tools/gen_site_data.py from patches/*.yaml. Do not edit.\n"
               "globalThis.X1700_PATCHES = " + json.dumps(data, indent=1) + ";\n")
(ROOT / "patches/patches.json").write_text(json.dumps(data, indent=1) + "\n")     # for tools/x1700_patcher.py (no PyYAML needed)
print(f"wrote {out.relative_to(ROOT)} and patches/patches.json: {len(data['patches'])} patch entries, result sha256 {data['resultSha256']}")

# X1600 (experimental page)
if models.get("X1600")["image"].exists():
    m = models.get("X1600")
    d = {"model": "DN-X1600", "fwName": m["fw_name"], "size": m["size"], "untested": False} | site_data("X1600")
    out = ROOT / "site/x1600/patches.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// GENERATED by tools/gen_site_data.py from patches/x1600/*.yaml. Do not edit.\n"
                   "globalThis.X1600_PATCHES = " + json.dumps(d, indent=1) + ";\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(d['patches'])} patch entries, result sha256 {d['resultSha256']}")
else:
    print("firmware/original/X1600FW.BIN not found: X1600 page data not regenerated")

# X600 (experimental page; different integrity rule and version)
if models.get("X600")["image"].exists():
    m = models.get("X600")
    d = {"model": "DN-X600", "fwName": m["fw_name"], "size": m["size"], "integrity": m["integrity"], "version": "v1.030",
         "untested": True} | site_data("X600")
    out = ROOT / "site/x600/patches.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// GENERATED by tools/gen_site_data.py from patches/x600/*.yaml. Do not edit.\n"
                   "globalThis.X600_PATCHES = " + json.dumps(d, indent=1) + ";\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(d['patches'])} patch entries, result sha256 {d['resultSha256']}")
else:
    print("firmware/original/X600FW.BIN not found: X600 page data not regenerated")
