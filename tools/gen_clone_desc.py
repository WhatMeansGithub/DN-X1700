#!/usr/bin/env python3
"""Generate clone-f411/src/desc_variants.h from the descriptors macOS received from the real X1700.

Each variant = the captured 385-byte config descriptor with a chosen SET of named changes applied.
Offsets are located by walking the descriptors, not hard-coded, and asserted.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
dev = (ROOT / "captures/macos-live-device-desc.bin").read_bytes()
cfg = (ROOT / "captures/macos-live-config-desc.bin").read_bytes()
assert len(dev) == 18 and len(cfg) == 385 and cfg[2:4] == b"\x81\x01"


def walk(blob):
    i = 0
    while i < len(blob):
        yield i, blob[i], blob[i + 1], blob[i + 2] if blob[i] > 2 else None
        i += blob[i]


iad0 = in_terms = out_terms = as_gen = cs_ep = fmt1 = None
in_terms, out_terms, as_gen, cs_ep, fmt1, iads = [], [], [], [], [], []
for off, ln, ty, st in walk(cfg):
    if ty == 0x0B:
        iads.append(off)
    elif ty == 0x24 and st == 2 and ln == 0x11:
        in_terms.append(off)                       # input terminal: nch +8, config +9..12, bmControls +14..15
    elif ty == 0x24 and st == 3 and ln == 0x0C:
        out_terms.append(off)                      # output terminal: bmControls +9..10
    elif ty == 0x24 and st == 1 and ln == 0x10:
        as_gen.append(off)                         # AS_GENERAL: bmControls +4, nch +10, config +11..14
    elif ty == 0x24 and st == 2 and ln == 6 and cfg[off + 3] == 1 and cfg[off + 4] == 3:
        fmt1.append(off)                           # FORMAT_TYPE_I, 3-byte subslot (the two 24-bit audio formats)
    elif ty == 0x25 and ln == 8:
        cs_ep.append(off)                          # CS iso endpoint: bmControls +4
assert cfg[iads[0] + 4] == 0xFF and len(in_terms) == 2 and len(out_terms) == 2 and len(as_gen) == 2 and len(cs_ep) == 2 and len(fmt1) == 2


def setb(c, off, data):
    c[off:off + len(data)] = bytes(data)


CHANGES = {
    "iad":   ("IAD0 bFunctionClass 0xFF -> 0x01", lambda c: setb(c, iads[0] + 4, [0x01])),
    "term":  ("IT/OT bmControls -> 0 (firmware stalls terminal controls)",
              lambda c: [setb(c, o + 14, [0, 0]) for o in in_terms] + [setb(c, o + 9, [0, 0]) for o in out_terms]),
    "as":    ("AS_GENERAL bmControls 0x05 -> 0 (active/valid alt setting controls)",
              lambda c: [setb(c, o + 4, [0]) for o in as_gen]),
    # Linux finds this one: bmControls bits 0-1 = pitch control present -> snd-usb-audio SETs it, the firmware STALLs, hw_params fails (-EPIPE).
    "pitch": ("CS iso endpoint bmControls 0x15 -> 0x14 (no pitch control)", lambda c: [setb(c, o + 4, [0x14]) for o in cs_ep]),
    "ep":    ("CS iso endpoint bmControls 0x15 -> 0", lambda c: [setb(c, o + 4, [0]) for o in cs_ep]),
    # What the real unit sends in MAC mode after init (usb.md): iso endpoints synchronous (0x0D) instead of adaptive (0x09).
    "sync":  ("iso EP bmAttributes 0x09 -> 0x0D (MAC-mode runtime rewrite)",
              lambda c: [setb(c, o, [0x0D]) for o in (161, 216)]),
    # Isolation test for the MPC: drop IAD1 + MIDI + HID, leave only the audio function (ifaces 0-2).
    "audioonly": ("keep only IAD0 audio function (ifaces 0-2), cut at IAD1",
                  lambda c: (c.__delitem__(slice(iads[1], None)), setb(c, 2, [iads[1] & 0xFF, iads[1] >> 8]), setb(c, 4, [3]))),
    # Bandwidth sanity for the FULL-SPEED clone only (NOT for the real unit): 2 ch / 16 bit = 176 B/ms <= 312.
    "fs2ch": ("FS bandwidth sanity: 8ch/24bit -> 2ch/16bit in terminals + AS + format",
              lambda c: [setb(c, o + 8, [2]) or setb(c, o + 9, [3, 0, 0, 0]) for o in in_terms]
              + [setb(c, o + 10, [2]) or setb(c, o + 11, [3, 0, 0, 0]) for o in as_gen]
              + [setb(c, o + 4, [2, 16]) for o in fmt1]),
}

VARIANTS = [
    ("v0 original", []),
    ("v1 iad", ["iad"]),
    ("v2 iad+term", ["iad", "term"]),
    ("v3 iad+term+as", ["iad", "term", "as"]),
    ("v4 iad+term+as+ep", ["iad", "term", "as", "ep"]),
    ("v5 iad+as (minimal)", ["iad", "as"]),
    ("v6 iad+as+fs2ch", ["iad", "as", "fs2ch"]),
    ("v7 iad+as+sync (real MAC-mode set)", ["iad", "as", "sync"]),
    ("v8 iad+as+sync+fs2ch (FS test for MPC)", ["iad", "as", "sync", "fs2ch"]),
    ("v9 = v8 descriptors, LENIENT stub (main.c)", ["iad", "as", "sync", "fs2ch"]),
    ("v10 = v8 + audio function only", ["iad", "as", "sync", "fs2ch", "audioonly"]),
    ("v11 = v8 + pitch fix (Linux)", ["iad", "as", "sync", "fs2ch", "pitch"]),
]

built = []
for name, parts in VARIANTS:
    c = bytearray(cfg)
    for p in parts:
        CHANGES[p][1](c)
    built.append((name, parts, bytes(c)))


def carr(name, b):
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return f"static const uint8_t {name}[{len(b)}] __attribute__((aligned(4))) = {{\n" + ",\n".join(rows) + ",\n};\n"


out = ["/* GENERATED by tools/gen_clone_desc.py - do not edit. */", "#pragma once", "#include <stdint.h>", ""]
out.append(carr("desc_device", dev))
for i, (name, parts, b) in enumerate(built):
    out.append(f"/* {name}: {' + '.join(parts) or 'unmodified'} */")
    out.append(carr(f"desc_cfg_v{i}", b))
out.append(f"#define NUM_VARIANTS {len(built)}")
out.append("static const uint8_t *const variant_cfg[NUM_VARIANTS] = {" + ", ".join(f"desc_cfg_v{i}" for i in range(len(built))) + "};")
(ROOT / "clone-f411/src").mkdir(parents=True, exist_ok=True)
(ROOT / "clone-f411/src/desc_variants.h").write_text("\n".join(out) + "\n")

for p, (d, _) in CHANGES.items():
    print(f"  {p:6s} {d}")
for i, (name, parts, b) in enumerate(built):
    print(f"{i}: {name:22s} bytes changed vs captured: {sum(1 for j in range(min(len(cfg), len(b))) if b[j] != cfg[j])}")
